    private void jLoadDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jLoadDataActionPerformed
        // TODO add your handling code here:
         // Sample 2D array: Rows = Years, Columns = Products
    double[][] productSales = {
        {300, 150, 700}, // Year 1
        {250, 200, 600}  // Year 2
    };
    
    final double SALES_LIMIT = 500.0;
    
    double totalSales = 0;
    int itemCount = 0;
    int overLimit = 0;
    int underLimit = 0;
    int yearsProcessed = productSales.length;

    // Loop through the 2D array in memory
    for (int year = 0; year < productSales.length; year++) {
        for (int product = 0; product < productSales[year].length; product++) {
            double sale = productSales[year][product];
            totalSales += sale;
            itemCount++;

            if (sale > SALES_LIMIT) {
                overLimit++;
            } else {
                underLimit++;
            }
        }
    }

    double averageSales = (itemCount > 0) ? (totalSales / itemCount) : 0;

    // Format the output string for the JTextArea (without Years Processed)
    StringBuilder output = new StringBuilder();
    output.append("DATA LOG\n");
    output.append("******************************************\n");
    output.append(String.format("Total Sales: R%.2f%n", totalSales));
    output.append(String.format("Average Sales: R%.2f%n", averageSales));
    output.append("Sales over limit: ").append(overLimit).append("\n");
    output.append("Sales under limit: ").append(underLimit).append("\n");
    output.append("******************************************");

    // 1. Display the sales summary inside the JTextArea
    txtDisplay.setText(output.toString());

    // 2. Display the years processed externally on the JLabel
    lblYearsProcessed.setText("Years Processed: " + yearsProcessed);
    }//GEN-LAST:event_jLoadDataActionPerformed

    private void jSaveProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jSaveProductActionPerformed
        // TODO add your handling code here:
            String content = txtDisplay.getText();

    if (content.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "No data to save. Please load product data first.");
        return;
    }

    // Saves data.txt in the root folder of your NetBeans project
    try (PrintWriter writer = new PrintWriter(new FileWriter("data.txt"))) {
        writer.print(content);
        JOptionPane.showMessageDialog(this, "Data successfully saved to data.txt");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error saving file: " + e.getMessage());
    }
    }//GEN-LAST:event_jSaveProductActionPerformed

